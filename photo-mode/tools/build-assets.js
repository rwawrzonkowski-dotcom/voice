/* Builds photo-mode/js/assets.js from the site's own drawings.
   Run from the repo root:  node photo-mode/tools/build-assets.js
   Why: the tool must work from file:// where textures from image files are blocked,
   so every built-in drawing is stored as an SVG string inside a classic script. */
var fs = require('fs');
var path = require('path');
var root = path.join(__dirname, '..', '..');

function read(p) { return fs.readFileSync(path.join(root, p), 'utf8'); }
function clean(svg) {
  return svg
    .replace(/<\?xml[^>]*\?>/g, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/>\s+</g, '><')
    .trim();
}

var out = {
  characters: {
    dibs: clean(read('img/dibs/dibs.svg')),
    dibsTrain: clean(read('img/dibs/dibs-train.svg')),
    wacker: clean(read('img/wacker/wacker.svg')),
    wackerFly: clean(read('img/wacker/wacker-fly.svg'))
  },
  symbols: {}
};
fs.readdirSync(path.join(root, 'img/symbols')).filter(function (f) { return /\.svg$/.test(f); }).sort().forEach(function (f) {
  out.symbols[f.replace(/\.svg$/, '')] = clean(read('img/symbols/' + f));
});

var js = '/* GENERATED by photo-mode/tools/build-assets.js. Do not edit by hand.\n' +
  '   Dibs and Wacker: Richard Wawrzonkowski (CC BY-SA 4.0). Symbols: Mulberry Symbols and OpenMoji (CC BY-SA 4.0), see NOTICE.md. */\n' +
  'window.DIBS_ASSETS = ' + JSON.stringify(out) + ';\n';
fs.writeFileSync(path.join(root, 'photo-mode/js/assets.js'), js);
console.log('assets.js', Math.round(js.length / 1024) + ' KB,', Object.keys(out.symbols).length, 'symbols');
